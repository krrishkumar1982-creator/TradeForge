export const ALL_METRICS_MAP = new Map<string, MetricDefinition>(
  METRIC_CATEGORIES.flatMap(cat => cat.metrics).map(m => [m.id, m])
);

export function getMetricById(id: string): MetricDefinition {
  const found = ALL_METRICS_MAP.get(id);
  if (found) return found;
  // Fallback if id not found
  return {
    id,
    name: id,
    category: 'General',
    description: 'Custom trading metric',
    unit: 'number',
    defaultChartType: 'line',
  };
}
